import 'dart:io';

import 'package:baocode/kernel/dsh/dsh_locate.dart';
import 'package:baocode/kernel/dsh/dsh_patch.dart';
import 'package:baocode/kernel/dsh/dsh_route.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;

/// The patch BaoCode runs dsh with: its text, the route it carries, and the
/// file it writes.
void main() {
  late Directory root;

  setUp(() => root = Directory.systemTemp.createTempSync('baocode-dsh-patch'));
  tearDown(() => root.deleteSync(recursive: true));

  String at(String relative) => p.join(root.path, relative);

  /// The route a machine wrote down: what the patch in these tests carries.
  const route = DshRoute(
    provider: 'stepcodev2',
    baseUrl: 'https://i-ai-gw.stepx.com/v1',
    apiKeyEnv: 'STEPCODEV2_API_KEY',
    model: 'deepseek-v4.1-flash',
    contextWindow: 512000,
  );

  /// A dsh at [version], found anywhere.
  DshInstall installAt(String version) => DshInstall(
    node: 'node',
    binJs: at(p.join('dsh', 'lib', 'bin.js')),
    version: version,
    packageDir: at('dsh'),
  );

  /// [dshHome] with the Git Bash plugin installed for the ACP profile.
  void installGitBash(String dshHome) {
    Directory(
      p.join(dshHome, 'profiles', 'acp', 'node_modules', 'dsh-gitbash-shell'),
    ).createSync(recursive: true);
  }

  test('the patch carries the route it is given', () {
    final text = DshPatch.content(version: '0.2.0-rc.2', route: route);

    expect(
      text.split('\n').first,
      '# Generated by BaoCode for dsh 0.2.0-rc.2. Do not edit.',
    );
    for (final line in [
      '- id: llm-pi-ai',
      "  name: '@deepseek-ai/dsh-llm-pi-ai'",
      '        apiKeyEnv: STEPCODEV2_API_KEY',
      '        api: openai-completions',
      '        baseURL: https://i-ai-gw.stepx.com/v1',
      '            contextWindow: 512000',
      '            input: [text, image]',
      '- id: acp',
      "  name: '@deepseek-ai/dsh-acp'",
      '  inject: [acpAppStartup]',
      '    provider: stepcodev2',
      '    model: deepseek-v4.1-flash',
    ]) {
      expect(text, contains(line));
    }
    expect(text, isNot(contains('tool-bash')));
    expect(text.endsWith('\n'), isTrue);
  });

  test('no route: the patch leaves the profile its own', () {
    final text = DshPatch.content(version: '0.2.0-rc.2');

    // dsh reads the model its own ACP profile is configured with, as it does
    // from dsh web: BaoCode declares none of its own.
    expect(text, isNot(contains('llm-pi-ai')));
    expect(text, isNot(contains('apiKeyEnv')));
    expect(text, isNot(contains('baseURL')));
    expect(text, isNot(contains('provider:')));
    expect(text, isNot(contains('model:')));
    expect(text, isNot(contains('  config:')));
    // The profile entry itself is still composed.
    expect(text, contains('- id: acp'));
    expect(text, contains('  inject: [acpAppStartup]'));
    expect(text.endsWith('\n'), isTrue);
  });

  test('a Git Bash found turns the bash tool on, and names no executor', () {
    final text = DshPatch.content(
      version: '0.2.0-rc.2',
      route: route,
      withBash: true,
    );

    expect(text, contains('- id: tool-bash'));
    expect(text, contains('  disabled: false'));
    // The executor is the plugin's own bundle patch (`gitbash-executor`): a row
    // of ours could not mount it — `bash-sandbox` is dsh's own id, and a patch
    // may not give an existing id another name (F28).
    expect(text, isNot(contains('dsh-gitbash-shell/shell')));
    expect(text, isNot(contains('bashPath')));
    // After the ACP entry: what a patch adds to the profile.
    expect(
      text.indexOf('- id: tool-bash'),
      greaterThan(text.indexOf('- id: acp')),
    );
  });

  test('a patch holds no key', () {
    final text = DshPatch.content(
      version: '0.2.0-rc.2',
      route: route,
      withBash: true,
    );

    expect(RegExp(r'[A-Za-z0-9_\-]{32,}').hasMatch(text), isFalse);
  });

  test(
    'the answerer is inserted where there is one, and left out where not',
    () {
      const bridge =
          'file:///C:/Users/me/AppData/Roaming/BaoCode/dsh/ask_bridge.mjs';
      final answerer = DshPatch.content(
        version: '0.2.0-rc.2',
        route: route,
        askBridge: bridge,
      );
      expect(answerer, contains('- insert:'));
      expect(answerer, contains('    - id: baocode-ask'));
      expect(
        answerer,
        contains("      name: '@deepseek-ai/dsh-tool-ask-user'"),
      );
      expect(answerer, contains('    - id: baocode-ask-bridge'));
      expect(answerer, contains("      name: '$bridge'"));
      // After the ACP entry: the insert is read once the profile is composed.
      expect(
        answerer.indexOf('- insert:'),
        greaterThan(answerer.indexOf('- id: acp')),
      );

      final without = DshPatch.content(version: '0.2.0-rc.2', route: route);
      expect(without, isNot(contains('baocode-ask')));
      expect(without, isNot(contains('insert:')));
    },
  );

  test('the token accountant is inserted even where no one answers', () {
    const bridge =
        'file:///C:/Users/me/AppData/Roaming/BaoCode/dsh/usage_bridge.mjs';
    final usage = DshPatch.content(version: '0.2.0-rc.2', usageBridge: bridge);
    expect(usage, contains('- insert:'));
    expect(usage, contains('    - id: baocode-usage-bridge'));
    expect(usage, contains("      name: '$bridge'"));
    // No answerer: a bot's conversation is still a conversation.
    expect(usage, isNot(contains('baocode-ask')));
    expect(usage, isNot(contains('dsh-tool-ask-user')));

    final both = DshPatch.content(
      version: '0.2.0-rc.2',
      askBridge: 'file:///tmp/ask_bridge.mjs',
      usageBridge: bridge,
    );
    expect(
      both.indexOf('baocode-ask-bridge'),
      lessThan(both.indexOf('baocode-usage-bridge')),
    );
  });

  test(
    'the one question runs headless on the same route, in its own folder',
    () {
      final text = DshPatch.askContent(
        version: '0.2.0-rc.2',
        sessionRoot: r'C:\Users\me\AppData\Local\Temp\ask-1\sessions',
        route: route,
      );

      expect(
        text.split('\n').first,
        '# Generated by BaoCode for dsh 0.2.0-rc.2. Do not edit.',
      );
      // The same route as the conversation's: the model a commit message is
      // written by is the one the project runs on.
      for (final line in [
        '- id: llm-pi-ai',
        '        apiKeyEnv: STEPCODEV2_API_KEY',
        '- id: agent-default-model',
        '    provider: stepcodev2',
        '    model: deepseek-v4.1-flash',
        // Answered in one reply, with nothing around it.
        '- id: system-prompt',
        '    personaPrefix: >-',
        "    personaSuffix: ''",
        // No title asked of the model, and no session of the user's.
        '- id: session-title-llm',
        '- id: session-persistence-jsonl',
        "    root: 'C:/Users/me/AppData/Local/Temp/ask-1/sessions'",
      ]) {
        expect(text, contains(line));
      }
      // The headless profile holds no ACP plugin: naming one is a patch that
      // cannot apply.
      expect(text, isNot(contains('dsh-acp')));
      expect(RegExp(r'[A-Za-z0-9_\-]{32,}').hasMatch(text), isFalse);
      expect(text, isNot(contains('!!')));
      expect(text.endsWith('\n'), isTrue);
    },
  );

  test('a question with no route declares no model either', () {
    final text = DshPatch.askContent(
      version: '0.2.0-rc.2',
      sessionRoot: '/tmp/ask-1/sessions',
    );

    // dsh's headless profile answers on whatever it is configured with; the
    // question is still one reply, with nothing kept in the user's sessions.
    expect(text, isNot(contains('llm-pi-ai')));
    expect(text, isNot(contains('agent-default-model')));
    expect(text, contains('- id: system-prompt'));
    expect(text, contains('- id: session-persistence-jsonl'));
  });

  test('a YAML tag cannot be written into the patch', () {
    expect(
      () => DshPatch.content(version: '0.2.0-!!js/function'),
      throwsArgumentError,
    );
  });

  test('the patch file is kept while it is what this dsh calls for', () async {
    final directory = at('app/dsh');
    final patch = await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      dshHome: at('dsh-home'),
    );

    final file = File(patch);
    expect(patch, p.join(directory, 'acp.patch.yml'));
    expect(
      await file.readAsString(),
      DshPatch.content(version: '0.2.0-rc.2', route: route),
    );

    file.setLastModifiedSync(DateTime(2001));
    final again = await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      dshHome: at('dsh-home'),
    );
    expect(again, patch);
    expect(file.lastModifiedSync().year, 2001, reason: 'it was written again');
  });

  test('a new dsh version is written a patch of its own', () async {
    final directory = at('app/dsh');
    final patch = await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      dshHome: at('dsh-home'),
    );
    final file = File(patch);

    expect(
      await DshPatch.ensure(
        install: installAt('0.3.0'),
        directory: directory,
        route: route,
        dshHome: at('dsh-home'),
      ),
      patch,
    );
    expect(
      await file.readAsString(),
      DshPatch.content(version: '0.3.0', route: route),
    );
  });

  test('a route changed is written into the patch again', () async {
    final directory = at('app/dsh');
    final patch = await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      dshHome: at('dsh-home'),
    );

    const other = DshRoute(
      provider: 'local',
      baseUrl: 'http://127.0.0.1:8080/v1',
      apiKeyEnv: 'LOCAL_API_KEY',
      model: 'local-model',
      contextWindow: 32000,
    );
    await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: other,
      dshHome: at('dsh-home'),
    );
    expect(
      await File(patch).readAsString(),
      DshPatch.content(version: '0.2.0-rc.2', route: other),
    );
  });

  test('no bash tool until the ACP profile has the plugin', () async {
    final directory = at('app/dsh');
    final dshHome = at('dsh-home');
    final patch = await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      withBash: true,
      dshHome: dshHome,
    );
    final file = File(patch);
    expect(await file.readAsString(), isNot(contains('tool-bash')));

    installGitBash(dshHome);
    await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      withBash: true,
      dshHome: dshHome,
    );
    expect(
      await file.readAsString(),
      DshPatch.content(version: '0.2.0-rc.2', route: route, withBash: true),
    );
  });

  test('the patch is the user\'s own file, in a folder of their own', () async {
    final directory = at('app/dsh');
    final patch = await DshPatch.ensure(
      install: installAt('0.2.0-rc.2'),
      directory: directory,
      route: route,
      dshHome: at('dsh-home'),
    );

    // 0700 and 0600: what only the user may read, as dsh's own config is.
    expect(FileStat.statSync(directory).mode & 0x1FF, 0x1C0);
    expect(FileStat.statSync(patch).mode & 0x1FF, 0x180);
  }, skip: Platform.isWindows ? 'file modes are POSIX' : false);
}
