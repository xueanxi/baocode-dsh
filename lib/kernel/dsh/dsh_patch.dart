import 'dart:io';

import 'package:bao_remote/local.dart' show AppPaths;
import 'package:path/path.dart' as p;

import '../../platform/data_dir.dart' show writeFileAtomically;
import 'dsh_locate.dart';
import 'dsh_route.dart';

/// The ACP profile patch BaoCode runs dsh with: the route this machine keeps
/// ([DshRoute]), and — where the Git Bash plugin is installed for it — the
/// `bash` tool.
///
/// The route is not in this file: a provider, an endpoint and a model belong
/// to the machine that runs dsh, not to the app (`dsh_route.dart`). With no
/// route file, the patch declares none and dsh runs on the model its own ACP
/// profile is configured with, as it does from dsh web.
///
/// The executor that tool runs on is not named here: installing
/// `dsh-gitbash-shell` mounts it through the plugin's own bundle patch
/// (`gitbash-executor`), whose resolver finds the bash. A row of ours cannot
/// do that — `bash-sandbox` is dsh's own `@deepseek-ai/dsh-bash-sandbox` id,
/// and a patch may not give an existing id another name (F28) — so the patch
/// only turns the tool on.
///
/// A patch replaces a plugin's whole `config` (F21), so each entry below is
/// written out in full rather than leaning on what the profile already has.
/// It holds no key: the credentials stay in `~/.dsh` (F24), read by dsh
/// itself.
///
/// A second patch, written for the app's own one question ([askContent]),
/// routes dsh's `headless` profile through the same route: what writes a
/// commit message is the model the conversation runs on.
abstract final class DshPatch {
  /// The patch file [ensure] writes in the folder it is given.
  static const fileName = 'acp.patch.yml';

  /// The patch file one question is asked with (`dsh_ask_io.dart`), written
  /// for that one run in its own folder (see [askContent]).
  static const askFileName = 'ask.patch.yml';

  /// The patch's first line, naming the dsh it was written for (its
  /// package's version, F3): the file is written again when that, or
  /// anything else in it, changes.
  static String header(String version) =>
      '# Generated by BaoCode for dsh $version. Do not edit.';

  /// The patch for a dsh at [version]; [route] is the model this machine runs
  /// it on, or null to leave the profile its own. [withBash] turns the `bash`
  /// tool on. dsh disables it on Windows, and the Git Bash executor the plugin
  /// mounts is what serves it. [askBridge] is the `file://` URL of the
  /// answerer written by `dsh_ask_bridge.dart`: with one, dsh's
  /// `ask_user_question` is mounted and the app's bridge answers it.
  static String content({
    required String version,
    DshRoute? route,
    bool withBash = false,
    String? askBridge,
  }) => _patch([
    header(version),
    '',
    if (route != null) ..._routeOf(route),
    '- id: acp',
    "  name: '@deepseek-ai/dsh-acp'",
    '  inject: [acpAppStartup]',
    if (route != null) ...[
      '  config:',
      '    provider: ${route.provider}',
      '    model: ${route.model}',
    ],
    if (withBash) ...['- id: tool-bash', '  disabled: false'],
    if (askBridge != null) ...[
      '- insert:',
      '    - id: baocode-ask',
      "      name: '@deepseek-ai/dsh-tool-ask-user'",
      '    - id: baocode-ask-bridge',
      "      name: '$askBridge'",
    ],
  ]);

  /// The patch one question is asked with, for a dsh at [version] (see
  /// `dsh_ask.dart`): [content]'s route, over the `headless` profile, told to
  /// answer in one reply and to reach for nothing; the session dsh writes for
  /// that one answer goes under [sessionRoot], this run's own folder, rather
  /// than `~/.dsh` — the question is the app's, and none of it belongs in the
  /// user's sessions.
  ///
  /// Its session's title is not asked of the model: a title is another
  /// request, and nothing lists the session this run makes.
  static String askContent({
    required String version,
    required String sessionRoot,
    DshRoute? route,
  }) => _patch([
    header(version),
    '',
    if (route != null) ..._routeOf(route),
    // dsh's own default model is its upstream's: without a route of ours the
    // question goes by whatever the headless profile is configured with.
    if (route != null) ...[
      '- id: agent-default-model',
      '  config:',
      '    provider: ${route.provider}',
      '    model: ${route.model}',
    ],
    '- id: system-prompt',
    '  config:',
    '    includeHarnessIdentity: false',
    '    includeRuntimeContext: false',
    '    personaPrefix: >-',
    '      Answer the message in one reply, with the answer alone: no',
    '      preamble, no commentary, and no tools.',
    "    personaSuffix: ''",
    '- id: session-title-llm',
    '  disabled: true',
    '- id: session-persistence-jsonl',
    '  config:',
    // Quoted: a Windows path starts with a drive letter and a colon.
    "    root: '${sessionRoot.replaceAll(r'\', '/')}'",
  ]);

  /// [route] as a patch entry: written out whole, a patch replacing a
  /// plugin's `config` (F21).
  static List<String> _routeOf(DshRoute route) => [
    '- id: llm-pi-ai',
    "  name: '@deepseek-ai/dsh-llm-pi-ai'",
    '  config:',
    '    providers:',
    '      ${route.provider}:',
    '        displayName: ${route.provider}',
    '        apiKeyEnv: ${route.apiKeyEnv}',
    '        api: openai-completions',
    '        baseURL: ${route.baseUrl}',
    '        models:',
    '          - id: ${route.model}',
    '            name: ${route.model}',
    '            contextWindow: ${route.contextWindow}',
    '            input: [text, image]',
  ];

  /// [lines] as the patch file's text, a newline at its end; a YAML tag in it
  /// — a `!!` in a name a machine wrote — throws rather than going in.
  static String _patch(List<String> lines) {
    final text = '${lines.join('\n')}\n';
    if (text.contains('!!')) {
      // A YAML tag where a machine wrote a version: never in a patch of ours,
      // whatever dsh would make of it.
      throw ArgumentError.value(text, 'patch', 'A YAML tag cannot go in it');
    }
    return text;
  }

  /// The patch file in [directory], written for [install], or kept as it is
  /// when it already says exactly that (same dsh version, same content).
  ///
  /// [withBash] says a Git Bash was found on this machine; the tool is turned
  /// on only where the ACP profile also has `dsh-gitbash-shell`, whose bundle
  /// patch mounts the executor it runs on (F26: naming an uninstalled plugin
  /// is ignored, so enabling the tool without it would only pretend bash is
  /// there). [dshHome] is where that profile is looked for: `DSH_HOME`, else
  /// `~/.dsh`; a test gives its own. [askBridge] is the answerer's `file://`
  /// URL (`dsh_ask_bridge.dart`), or null where no question endpoint could be
  /// started. [route] is the machine's own (`dsh_route.dart`), or null for
  /// the profile's.
  static Future<String> ensure({
    required DshInstall install,
    required String directory,
    DshRoute? route,
    bool withBash = false,
    String? askBridge,
    String? dshHome,
  }) async {
    final file = File(p.join(directory, fileName));
    final text = content(
      version: install.version,
      route: route,
      withBash: withBash && await _pluginInstalled(dshHome),
      askBridge: askBridge,
    );
    try {
      if (await file.readAsString() == text) return file.path;
    } on FileSystemException {
      // Not there yet (or unreadable): written below.
    }
    await Directory(directory).create(recursive: true);
    // The user's own: dsh's config is read by them and dsh alone.
    if (!Platform.isWindows) await Process.run('chmod', ['700', directory]);
    await writeFileAtomically(file, text);
    if (!Platform.isWindows) await Process.run('chmod', ['600', file.path]);
    return file.path;
  }

  /// Whether the ACP profile has `dsh-gitbash-shell` installed: its bundle
  /// patch is what mounts the Git Bash executor the `bash` tool runs on.
  static Future<bool> _pluginInstalled(String? dshHome) async {
    final home = dshHome ?? _dshHome();
    if (home.isEmpty) return false;
    final plugin = Directory(
      p.join(home, 'profiles', 'acp', 'node_modules', 'dsh-gitbash-shell'),
    );
    return plugin.exists();
  }

  /// Where dsh keeps its profiles: `DSH_HOME` if set, else `~/.dsh`, as dsh
  /// itself defaults it.
  static String _dshHome() {
    final environment = Platform.environment;
    final named = environment['DSH_HOME']?.trim() ?? '';
    if (named.isNotEmpty) return named;
    final home = AppPaths.home(environment);
    return home.isEmpty ? '' : p.join(home, '.dsh');
  }
}
